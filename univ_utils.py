def normalize_text(s: str) -> str:
    if s is None:
        return ""
    s = unicodedata.normalize("NFKC", str(s)).strip()
    s = re.sub(r"\s+", "", s)
    return s

def canonical_university_name(name: str) -> str:
    s = normalize_text(name)
    if not s:
        return ""
    if s in ALIASES:
        return ALIASES[s]
    # 「○○大」表記を一般的な正式名称へ
    if s.endswith("大") and not s.endswith("大学"):
        cand = s + "学"
        if cand in ALIASES:
            return ALIASES[cand]
        return s + "学"
    return s

def cover_university(pref_name: str) -> str:
    return PREF_COVER.get(normalize_text(pref_name), "")

def match_to_image_name(name: str, image_names: list[str]) -> str:
    """入力名を画像ライブラリ上の実ファイル名へ寄せる。"""
    canon = canonical_university_name(name)
    if not canon:
        return ""
    stems = {normalize_text(x): x for x in image_names}
    if canon in stems:
        return stems[canon]
    # alias/部分一致
    for norm, original in stems.items():
        if canon in norm or norm in canon:
            return original
    return ""
